[h2] Content [/h2]
This mod adds 7 black cards and 4 white cards, each of which comes from a well-known Chinese idiom about military tactics,
originating from ancient Chinese classics (mostly the Art of War by Sun Tsu, or the 36 Stratagems)
If you are interested in the stories behind them, you can google the card names (or ask me in discord channels)

[h2] Balance [/h2]
I tried to be conservative when designing these cards so that they roughly match the power of vanilla cards.
They shouldn't be too strong; instead I expect them to be interesting in a way so that
they can bring great advantages if used in the right manner and/or with the right combo.

[h2] Weighting [/h2]
The weight of all cards in this mod is raised to 1.5x. Might add an option to control that in future updates.

[h2] Mod Dependencies [/h2]
Requires [u] Glacies' Collection[/u] (above this mod) and [u] Glac Terminal[/u] (below this mod).
[u] Better Codex[/u] is highly recommended.

[h2] Achievements [/h2]
This mod adds a total of 13 achievements. All achievements of this mod must be unlocked in vanilla gamemodes.
The unlock condition of many achievements is hidden, but their title serves as a hint. Google them.
[b] To see and unlock the achievements, [u] Achievement Centre[/u] is required. [/b]
